"""Storage-independent interface consumed by Host."""

from __future__ import annotations

from typing import Protocol
from typing import TYPE_CHECKING
from typing import AsyncContextManager, Awaitable, Callable

if TYPE_CHECKING:
    from autoagent.agent.recording import LLMCallRecord

from autoagent.core.compiler.snapshot import WorkflowDefinitionSnapshot
from autoagent.core.runtime.events import RuntimeEvent
from autoagent.core.runtime.graph_checkpoint import RuntimeGraphCheckpoint
from autoagent.core.runtime.user_events import UserEvent

from .models import OperatorDefinition, Page, PersistenceHealth, ReadView


class Persistence(Protocol):
    async def business_history(self, member: dict, kind: str, **options): ...
    async def business_value(self, member: dict, reference: dict, *, pointer: str | None = None): ...
    async def business_position(self, snapshot: dict, position: dict): ...
    async def business_order(self, snapshot: dict, earlier: dict, later: dict, *, limit: int): ...
    async def query_projection_status(self) -> dict: ...
    async def build_query_projections(self, *, rebuild: bool = False) -> dict: ...
    async def extension_operation(self, factory: Callable, method: str, *args, **kwargs): ...
    async def execution_diagnosis(self, invocation_id: str, *, limit: int = 20) -> dict | None: ...
    async def history_identity(self) -> str: ...
    async def invocation_summary(self, invocation_id: str) -> dict | None: ...
    async def capture_execution_evidence(self, invocation_id: str, *, limit: int = 1000) -> dict | None: ...
    async def inspect_execution_state(self, invocation_id: str, *, sequence: int, scope: str | None = None, pointer: str | None = None, field: str | None = None) -> dict | None: ...
    async def load_execution_context(self, invocation_id: str, *, sequence: int, scope: str, pointer: str | None = None) -> dict | None: ...
    async def execution_events(self, invocation_id: str, **options) -> Page | None: ...
    async def execution_event(self, invocation_id: str, event_id: str, **options) -> dict | None: ...
    async def execution_state(self, invocation_id: str, *, settled_version: tuple | None = None) -> dict | None: ...
    async def compare_workflow_revisions(self, base: str, target: str, **options) -> dict | None: ...
    async def revision_comparison_object(self, base: str, target: str, kind: str, identity: str) -> dict | None: ...
    async def session_information(self, session_id: str, *, excluded_workflow_ids: tuple[str, ...] = ()) -> dict | None: ...
    async def session_history(self, session_id: str, **options) -> Page | None: ...
    async def session_workflows(self, session_id: str, **options) -> Page | None: ...
    async def control_metadata(self, invocation_id: str, registered: tuple[str, ...], **options) -> dict | None: ...
    async def trace_head(self, invocation_id: str) -> dict | None: ...
    async def wait_trace_commit(self, revision: int, timeout: float) -> int: ...
    def execution_notifications(self, invocation_id: str) -> AsyncContextManager[tuple[int, Callable[[int, float, str], Awaitable[int]]]]: ...
    async def release_trace_dataset(self, snapshot_id: str) -> None: ...
    async def record_llm_call(self, record: LLMCallRecord) -> None: ...
    async def admit_llm_call(self, record: LLMCallRecord, checks) -> None: ...
    async def mark_llm_call_unsettled(self, llm_call_id: str) -> None: ...
    async def token_usage(self, *, query=None, **filters): ...
    async def execution_snapshot(self, invocation_id: str, *, view: ReadView = "accepted") -> dict | None: ...
    async def activation_candidates(self, now_us: int, *, limit: int = 32, cursor: str | None = None) -> Page: ...
    async def register_workflow(self, snapshot: WorkflowDefinitionSnapshot) -> str: ...
    async def register_operator(self, definition: OperatorDefinition) -> str: ...
    async def get_workflow(self, revision_id: str) -> dict | None: ...
    async def get_operator(self, definition_id: str) -> dict | None: ...
    async def list_workflows(
        self,
        *,
        workflow_id: str | None = None,
        limit: int = 100,
        cursor: tuple | None = None,
        excluded_workflow_ids: tuple[str, ...] = (),
    ) -> Page: ...
    async def list_operators(
        self,
        *,
        operator_id: str | None = None,
        limit: int = 100,
        cursor: tuple | None = None,
    ) -> Page: ...
    async def workflow_catalog(self, *, registered_ids: tuple[str, ...] = (), search: str = "", limit: int = 100, cursor: tuple | None = None, registered_only: bool = False, excluded_workflow_ids: tuple[str, ...] = ()) -> Page: ...
    async def workflow_revisions(self, workflow_id: str, *, prefix: str | None = None, limit: int = 100, cursor: tuple | None = None) -> Page: ...
    async def workflow_graph(self, revision_id: str) -> dict | None: ...
    async def workflow_object(self, revision_id: str, kind: str, identity: str) -> dict | None: ...
    async def trace_page(self, kind: str, invocation_id: str | None = None, **filters) -> Page | None: ...
    async def execution_sessions(self, **filters) -> Page: ...
    async def execution_trace(self, invocation_id: str) -> dict | None: ...
    async def execution_family(self, invocation_id: str) -> dict | None: ...
    async def trace_dataset(self, invocation_id: str, **options) -> dict | None: ...
    async def trace_dataset_page(self, snapshot_id: str, kind: str, page: int) -> dict: ...
    async def execution_timeline(self, invocation_id: str) -> dict | None: ...
    async def timeline_page(self, invocation_id: str, **filters) -> Page | None: ...
    async def timeline_position(self, invocation_id: str, kind: str, identity: str, **filters) -> dict | None: ...
    async def timeline_event_groups(self, invocation_id: str, **filters) -> dict | None: ...
    async def timeline_markers(self, invocation_id: str, **filters) -> Page | None: ...
    async def timeline_frame(self, invocation_id: str, **position) -> dict | None: ...
    async def execution_record(self, invocation_id: str, kind: str, identity: str) -> dict | None: ...
    async def trace_value(self, invocation_id: str, kind: str, identity: str, field: str, *, pointer: str | None = None) -> dict | None: ...
    async def execution_stages(self, invocation_id: str, occurrence_id: str, **filters) -> Page | None: ...
    async def execution_stage_value(self, invocation_id: str, occurrence_id: str, event_id: str, field: str, *, pointer: str | None = None) -> dict | None: ...
    async def append(self, event: RuntimeEvent) -> None: ...
    async def append_runtime_event(
        self, event: RuntimeEvent, *, operator_definition_id: str | None = None
    ) -> int: ...
    async def append_user_event(self, event: UserEvent) -> None: ...
    async def get_runtime_event(self, event_id: str) -> RuntimeEvent | None: ...
    async def get_user_event(self, event_id: str) -> UserEvent | None: ...
    async def runtime_events(
        self,
        session_id: str,
        *,
        after: int = 0,
        limit: int = 100,
        view: ReadView = "durable",
        invocation_id: str | None = None,
    ) -> Page: ...
    async def user_events(
        self,
        invocation_id: str,
        *,
        after: int = 0,
        occurrence_id: str | None = None,
        limit: int = 100,
        view: ReadView = "durable",
    ) -> Page: ...
    async def save_checkpoint(self, checkpoint: RuntimeGraphCheckpoint, *, pinned: bool = False,
        reason: str = "automatic", keep_latest: int | None = None) -> str: ...
    async def checkpoint_info(self, checkpoint_id: str) -> dict | None: ...
    async def set_checkpoint_pinned(self, checkpoint_id: str, pinned: bool) -> dict | None: ...
    async def import_checkpoint(self, checkpoint: RuntimeGraphCheckpoint) -> str: ...
    async def get_checkpoint(
        self, checkpoint_id: str
    ) -> RuntimeGraphCheckpoint | None: ...
    async def list_checkpoints(
        self, session_id: str, *, limit: int = 100, cursor: tuple | None = None
    ) -> Page: ...
    async def list_sessions(
        self,
        *,
        limit: int = 100,
        cursor: tuple | None = None,
        view: ReadView = "durable",
    ) -> Page: ...
    async def get_session(
        self, session_id: str, *, view: ReadView = "durable"
    ) -> dict | None: ...
    async def list_invocations(
        self,
        *,
        workflow_revision_id: str | None = None,
        session_id: str | None = None,
        root_invocation_id: str | None = None,
        status: str | None = None,
        include_planned: bool = False,
        limit: int = 100,
        cursor: tuple | None = None,
        view: ReadView = "durable",
    ) -> Page: ...
    async def get_invocation(
        self, invocation_id: str, *, view: ReadView = "durable"
    ) -> dict | None: ...
    async def graph_changes(
        self,
        invocation_id: str,
        *,
        after_sequence: int = 0,
        limit: int = 100,
        root_graph: bool = False,
        view: ReadView = "durable",
    ) -> Page: ...
    async def list_nodes(
        self,
        invocation_id: str,
        *,
        limit: int = 100,
        cursor: tuple | None = None,
        view: ReadView = "durable",
    ) -> Page: ...
    async def list_calls(
        self,
        invocation_id: str,
        *,
        occurrence_id: str | None = None,
        limit: int = 100,
        cursor: tuple | None = None,
        view: ReadView = "durable",
    ) -> Page: ...
    async def list_waits(
        self,
        invocation_id: str,
        *,
        limit: int = 100,
        cursor: tuple | None = None,
        view: ReadView = "durable",
    ) -> Page: ...
    async def node_detail(
        self, invocation_id: str, occurrence_id: str, *, view: ReadView = "durable"
    ) -> dict | None: ...
    async def call_detail(
        self, invocation_id: str, call_id: str, *, view: ReadView = "durable"
    ) -> dict | None: ...
    async def wait_detail(
        self, invocation_id: str, wait_id: str, *, view: ReadView = "durable"
    ) -> dict | None: ...
    async def edge_detail(
        self,
        invocation_id: str,
        edge_id: str,
        *,
        limit: int = 100,
        evaluations_cursor: tuple | None = None,
        changes_cursor: tuple | None = None,
        view: ReadView = "durable",
    ) -> dict: ...
    async def statistics(
        self, entity: str, *, workflow_revision_id: str | None = None
    ) -> tuple[dict, ...]: ...
    async def resolve(self, reference: dict | None) -> dict: ...
    async def flush(self) -> None: ...
    async def read_recovery_bundle(self, root_invocation_id: str, *, full_history: bool = False) -> dict: ...
    async def read_checkpoint_position(self, session_id: str, sequence: int, *, full_history: bool = False) -> dict: ...

    async def initialize_fork(self, events: tuple[RuntimeEvent, ...]) -> None: ...

    async def fork_position(self, session_id: str, sequence: int) -> dict | None: ...
    async def projection_cache_statistics(self) -> dict: ...
    async def health(self) -> PersistenceHealth: ...
    async def close(self) -> None: ...
    async def delete_checkpoint(self, checkpoint_id: str) -> bool: ...
    async def delete_workflow(self, revision_id: str) -> None: ...
    async def delete_operator(self, definition_id: str) -> None: ...
    async def purge_root_graph(self, root_invocation_id: str) -> None: ...
    async def rebuild_projections(self) -> None: ...
    async def gc_artifacts(self) -> int: ...
